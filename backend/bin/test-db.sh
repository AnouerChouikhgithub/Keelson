#!/usr/bin/env bash
#
# Throwaway PostgreSQL 16 for the backend test suite.
#
#   bin/test-db.sh start   # start a labelled, volume-free container and wire .env.test.local
#   bin/test-db.sh stop    # remove the helper's container and generated env file
#   bin/test-db.sh status  # show the container and port, if running
#
# Safety rules:
#   - The container carries a `keelson.test-db` label tied to this checkout; the
#     helper refuses to reuse, stop or remove any container that lacks it, and it
#     fails on a name collision instead of deleting an unknown container.
#   - It refuses to start while `.env.test.local` already exists, including a
#     file from a previous helper run. This avoids overwriting any developer
#     configuration; `stop` removes the generated file only after verifying
#     the matching owned container.
#   - The container has no volume and publishes an ephemeral loopback port
#     (`-p 127.0.0.1::5432`), because fixed ports are often reserved on Windows.
#     The real port is read back from Docker, so nothing has to be guessed.
set -euo pipefail

CONTAINER="${KEELSON_TEST_DB_CONTAINER:-keelson-test-db}"
IMAGE="${KEELSON_TEST_DB_IMAGE:-postgres:16-alpine}"
DB_USER="${KEELSON_TEST_DB_USER:-keelson}"
DB_PASSWORD="${KEELSON_TEST_DB_PASSWORD:-keelson}"
DB_NAME="${KEELSON_TEST_DB_NAME:-keelson_test}"
BACKEND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${BACKEND_DIR}/.env.test.local"
ENV_MARKER="# generated by bin/test-db.sh"
REPO_ID="$(printf '%s' "${BACKEND_DIR}" | cksum | awk '{print $1}')"
OWNED_LABEL="keelson.test-db"
REPO_LABEL="keelson.test-db.repo"

usage() {
    sed -n '2,18p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit "${1:-0}"
}

require_docker() {
    command -v docker >/dev/null 2>&1 || {
        echo "error: docker is not on PATH." >&2
        exit 1
    }
    docker info >/dev/null 2>&1 || {
        echo "error: the Docker engine is not running. Start Docker Desktop and retry." >&2
        exit 1
    }
}

container_exists() {
    docker inspect --type container "${CONTAINER}" >/dev/null 2>&1
}

container_running() {
    [ "$(docker inspect --format '{{.State.Running}}' "${CONTAINER}" 2>/dev/null)" = "true" ]
}

label() {
    docker inspect --format "{{ index .Config.Labels \"$1\" }}" "${CONTAINER}" 2>/dev/null || true
}

# Ownership requires both labels: a unique marker and this checkout's id.
container_is_owned() {
    [ "$(label "${OWNED_LABEL}")" = "1" ] || return 1
    [ "$(label "${REPO_LABEL}")" = "${REPO_ID}" ]
}

require_owned_container() {
    if ! container_is_owned; then
        echo "error: container '${CONTAINER}' exists but was not created by this helper." >&2
        echo "Refusing to reuse, stop or remove it. Remove it yourself, or set" >&2
        echo "KEELSON_TEST_DB_CONTAINER to a different name." >&2
        exit 1
    fi
}

host_port() {
    docker port "${CONTAINER}" 5432/tcp 2>/dev/null | head -n1 | awk -F: '{print $NF}'
}

env_file_is_generated() {
    [ -f "${ENV_FILE}" ] && [ "$(head -n1 "${ENV_FILE}" 2>/dev/null)" = "${ENV_MARKER}" ]
}

# Refuse before starting/altering anything so no pre-existing file is overwritten.
assert_env_file_writable() {
    if [ -e "${ENV_FILE}" ]; then
        echo "error: ${ENV_FILE} already exists." >&2
        echo "Refusing to overwrite it. Move it aside before starting this disposable test database." >&2
        exit 1
    fi
}

ensure_line() {
    local key="$1"
    local value="$2"
    grep -qE "^${key}=" "${ENV_FILE}" || printf '%s="%s"\n' "${key}" "${value}" >>"${ENV_FILE}"
}

write_env_file() {
    local port="$1"
    {
        echo "${ENV_MARKER}"
        echo "# Remove with: backend/bin/test-db.sh stop"
        echo "DATABASE_URL=\"postgresql://${DB_USER}:${DB_PASSWORD}@127.0.0.1:${port}/${DB_NAME}?serverVersion=16&charset=utf8\""
    } >"${ENV_FILE}"

    echo "Wrote ${ENV_FILE} for 127.0.0.1:${port}/${DB_NAME}."
}

restore_env_file() {
    if env_file_is_generated; then
        rm -f "${ENV_FILE}"
        echo "Removed the .env.test.local created by this run."
    fi
}

remove_created_container() {
    if container_exists && container_is_owned; then
        docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
        echo "Removed the container created by this run."
    fi
}

wait_until_ready() {
    local attempt
    for attempt in $(seq 1 60); do
        if docker exec "${CONTAINER}" pg_isready -U "${DB_USER}" -d "${DB_NAME}" >/dev/null 2>&1; then
            return 0
        fi
        sleep 1
    done
    return 1
}

start() {
    require_docker
    assert_env_file_writable

    local created=0
    if container_exists; then
        require_owned_container
        if container_running; then
            echo "Reusing helper container ${CONTAINER}."
        else
            # Stopped containers from this helper are disposable; recreate them.
            docker rm -f "${CONTAINER}" >/dev/null
        fi
    fi

    if ! container_exists; then
        docker run -d --name "${CONTAINER}" --rm \
            --label "${OWNED_LABEL}=1" \
            --label "${REPO_LABEL}=${REPO_ID}" \
            -e POSTGRES_USER="${DB_USER}" \
            -e POSTGRES_PASSWORD="${DB_PASSWORD}" \
            -e POSTGRES_DB="${DB_NAME}" \
            --tmpfs /var/lib/postgresql/data:rw \
            -p 127.0.0.1::5432 "${IMAGE}" >/dev/null
        created=1
    fi

    if ! wait_until_ready; then
        echo "error: ${CONTAINER} did not become ready within 60s. Last log lines:" >&2
        docker logs --tail 30 "${CONTAINER}" >&2 || true
        [ "${created}" -eq 1 ] && remove_created_container
        exit 1
    fi

    local port
    port="$(host_port)"
    if [ -z "${port}" ]; then
        echo "error: could not read the published port for ${CONTAINER}." >&2
        [ "${created}" -eq 1 ] && remove_created_container
        exit 1
    fi

    write_env_file "${port}"

    if ! (cd "${BACKEND_DIR}" &&
        php bin/console doctrine:database:create --if-not-exists --env=test >/dev/null &&
        php bin/console doctrine:migrations:migrate --env=test --no-interaction >/dev/null); then
        echo "error: creating or migrating the test database failed; see the console output above." >&2
        restore_env_file
        [ "${created}" -eq 1 ] && remove_created_container
        exit 1
    fi

    rm -f "${ENV_FILE}.keelson-prev"
    echo "Test database is migrated. Run: cd backend && php bin/phpunit"
}

stop() {
    require_docker
    if container_exists; then
        require_owned_container
        docker rm -f "${CONTAINER}" >/dev/null
        echo "Removed helper container ${CONTAINER}."
    else
        echo "No helper container named ${CONTAINER} exists."
    fi

    if env_file_is_generated; then
        if ! container_exists; then
            rm -f "${ENV_FILE}"
            echo "Deleted the generated .env.test.local."
        else
            echo "Left ${ENV_FILE} in place because the helper container still exists."
        fi
    elif [ -f "${ENV_FILE}" ]; then
        echo "Left ${ENV_FILE} in place: it was not generated by this script."
    fi
}

status() {
    require_docker
    if ! container_exists; then
        echo "${CONTAINER} is not running."
        if env_file_is_generated; then
            echo "A generated .env.test.local remains; run 'bin/test-db.sh stop' to clean it up."
        fi
        exit 1
    fi
    require_owned_container
    if container_running; then
        echo "${CONTAINER} is running on 127.0.0.1:$(host_port)/${DB_NAME}."
    else
        echo "${CONTAINER} exists but is stopped."
    fi
}

case "${1:-}" in
    start) start ;;
    stop) stop ;;
    status) status ;;
    -h|--help|help|'') usage 0 ;;
    *) echo "Unknown command: $1" >&2; usage 1 ;;
esac
