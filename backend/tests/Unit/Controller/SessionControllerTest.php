<?php

declare(strict_types=1);

namespace App\Tests\Unit\Controller;

use App\Controller\SessionController;
use App\Entity\Principal;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\Security\Core\Authentication\Token\NullToken;
use Symfony\Component\Security\Core\Authentication\Token\Storage\TokenStorage;
use Symfony\Component\Security\Core\Authentication\Token\UsernamePasswordToken;
use Symfony\Component\Security\Core\User\UserInterface;
use Symfony\Component\Security\Csrf\CsrfToken;
use Symfony\Component\Security\Csrf\CsrfTokenManagerInterface;

final class SessionControllerTest extends TestCase
{
    private const ANONYMOUS = ['authenticated' => false, 'user' => null, 'logout' => null];

    public function testAnonymousPayloadCarriesNoIdentityOrToken(): void
    {
        $csrf = $this->createMock(CsrfTokenManagerInterface::class);
        // A signed-out caller must not create a CSRF token (and therefore no
        // session) just by probing.
        $csrf->expects(self::never())->method('getToken');

        $response = (new SessionController($this->tokenStorage(), $csrf))->session();

        self::assertSame(200, $response->getStatusCode());
        self::assertSame(self::ANONYMOUS, $this->payload($response));
        self::assertStringContainsString('no-store', (string) $response->headers->get('Cache-Control'));
        self::assertStringContainsString('private', (string) $response->headers->get('Cache-Control'));
    }

    public function testEmptyTokenIsAnonymous(): void
    {
        $storage = new TokenStorage();
        $storage->setToken(new NullToken());

        $response = (new SessionController($storage, $this->createMock(CsrfTokenManagerInterface::class)))->session();

        self::assertSame(self::ANONYMOUS, $this->payload($response));
    }

    public function testAuthenticatedPayloadExposesOwnIdentityAndLogoutToken(): void
    {
        $principal = $this->principal('11111111-1111-4111-8111-111111111111');
        $principal->updateProfile('Amina Trabelsi', 'amina@example.test', true);

        $csrf = $this->createMock(CsrfTokenManagerInterface::class);
        $csrf->expects(self::once())
            ->method('getToken')
            // Must match the token id Symfony's LogoutListener validates by
            // default (see security.yaml `enable_csrf: true`).
            ->with('logout')
            ->willReturn(new CsrfToken('logout', 'csrf-value-for-logout'));

        $response = (new SessionController($this->tokenStorage($principal), $csrf))->session();

        self::assertSame(200, $response->getStatusCode());
        self::assertSame([
            'authenticated' => true,
            'user' => [
                'id' => '11111111-1111-4111-8111-111111111111',
                'email' => 'amina@example.test',
                'displayName' => 'Amina Trabelsi',
            ],
            'logout' => [
                'url' => '/logout',
                'csrfToken' => 'csrf-value-for-logout',
            ],
        ], $this->payload($response));
        self::assertStringContainsString('no-store', (string) $response->headers->get('Cache-Control'));
    }

    public function testNonPrincipalUserIsNotReportedAsAuthenticated(): void
    {
        $response = (new SessionController(
            $this->tokenStorage($this->createMock(UserInterface::class)),
            $this->createMock(CsrfTokenManagerInterface::class),
        ))->session();

        self::assertSame(self::ANONYMOUS, $this->payload($response));
    }

    private function tokenStorage(?UserInterface $user = null): TokenStorage
    {
        $storage = new TokenStorage();
        if ($user !== null) {
            $storage->setToken(new UsernamePasswordToken($user, 'main', $user->getRoles()));
        }

        return $storage;
    }

    /**
     * Principal's identifier is generated by Doctrine on persist, so a unit
     * test sets it reflectively instead of reaching for a database.
     */
    private function principal(string $id): Principal
    {
        $principal = new Principal('https://identity.example/oidc', 'user-123');
        (new \ReflectionProperty(Principal::class, 'id'))->setValue($principal, $id);

        return $principal;
    }

    /** @return array<string, mixed> */
    private function payload(JsonResponse $response): array
    {
        $decoded = json_decode((string) $response->getContent(), true, 512, \JSON_THROW_ON_ERROR);
        self::assertIsArray($decoded);

        return $decoded;
    }
}
